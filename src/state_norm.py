"""Write log1p(CP10k)-normalised copies of the 2025 splits, for STATE training.

Why this exists: `state tx infer` clips its output to [0, 14]. That bound is
only sensible in log1p space (log1p(1.2M) ~= 14). Our first training run set
`is_log1p=false`, which is a true statement about the raw 2025 counts but puts
the model in count space -- where the clip saturates every highly expressed
gene. The symptom was de_wilcoxon_lfc_nmae stuck at its -6.0 penalty cap while
direction metrics looked fine: right genes, wrong magnitudes.

`normalize_counts=true` does not help: in cell-load 0.10.4 that option is
stored and round-tripped but never applied to any data.

So we normalise on disk and then tell cell-load the truth (`is_log1p=true`).

Done by transforming `X/data` in place on a copy: CP10k + log1p is per-row and
does not change the sparsity pattern, so `indices`/`indptr` are untouched and
we never hold 1.9B nonzeros in memory.

The ORIGINALS stay put -- scoring needs real raw counts for the ground-truth
arm, and only the model's input/output space changes here.

Run:
    modal run --detach src/state_norm.py
"""

import modal

from common import REHEARSAL, VOL, VOL_PATH, app, cpu_image

NORM_DIR = f"{VOL_PATH}/state/norm"
TOML_PATH = f"{VOL_PATH}/state/vcc2025_norm.toml"
TARGET_SUM = 1e4

SPLITS = {
    "train": ("adata_Training.h5ad", "pert_counts_Training.csv"),
    "val": ("adata_Validation.h5ad", "pert_counts_Validation.csv"),
    "test": ("adata_Test.h5ad", "pert_counts_Test.csv"),
}
CELL_TYPE = "H1"
CONTROL_PERT = "non-targeting"


@app.function(
    image=cpu_image, volumes={VOL_PATH: VOL},
    cpu=4.0, memory=16384, timeout=60 * 60 * 5,
)
def normalize(force: bool = False, rows_per_chunk: int = 20000):
    import csv
    import os
    import shutil
    import time

    import h5py
    import numpy as np

    os.makedirs(NORM_DIR, exist_ok=True)

    for split, (h5, _) in SPLITS.items():
        src, dest = f"{REHEARSAL}/{h5}", f"{NORM_DIR}/{h5}"
        if os.path.exists(dest) and not force:
            print(f"[{split}] {h5} already normalised, skipping")
            continue
        t0 = time.time()
        print(f"[{split}] copying {os.path.getsize(src)/1e9:.2f} GB ...",
              flush=True)
        shutil.copy2(src, dest)
        VOL.commit()

        with h5py.File(dest, "r+") as h:
            X = h["X"]
            enc = X.attrs.get("encoding-type")
            if enc != "csr_matrix":
                raise RuntimeError(f"expected csr_matrix, got {enc!r}")
            if h.get("uns") is not None and "log1p" in h["uns"]:
                print(f"[{split}] already carries uns/log1p -- not redoing")
                continue
            indptr = X["indptr"][:]
            data = X["data"]
            n_rows = len(indptr) - 1
            print(f"[{split}] {n_rows} cells, {data.shape[0]:,} nonzeros")

            for lo in range(0, n_rows, rows_per_chunk):
                hi = min(lo + rows_per_chunk, n_rows)
                a, b = int(indptr[lo]), int(indptr[hi])
                if b <= a:
                    continue
                d = data[a:b].astype(np.float64)
                # Row sums from indptr offsets, without materialising the rows.
                # bincount over a repeated row index rather than reduceat,
                # which mis-handles empty rows (start == next start).
                rowlen = (indptr[lo + 1:hi + 1] - indptr[lo:hi]).astype(np.int64)
                rows = np.repeat(np.arange(hi - lo), rowlen)
                sums = np.bincount(rows, weights=d, minlength=hi - lo)
                scale = np.ones(hi - lo, dtype=np.float64)
                nz = sums > 0
                scale[nz] = TARGET_SUM / sums[nz]
                rep = np.repeat(scale, rowlen)
                data[a:b] = np.log1p(d * rep).astype(data.dtype)
                if (lo // rows_per_chunk) % 5 == 0:
                    print(f"  [{split}] {hi}/{n_rows} rows "
                          f"({time.time()-t0:.0f}s)", flush=True)

            # Mark it, so cell-load's own detection agrees with our config.
            uns = h.require_group("uns")
            uns.create_dataset("log1p", data=np.array([1], dtype=np.int8))
        VOL.commit()
        print(f"[{split}] normalised in {time.time()-t0:.0f}s")

    perts = {}
    for split, (_, csvname) in SPLITS.items():
        with open(f"{REHEARSAL}/{csvname}", newline="") as fh:
            perts[split] = sorted({r["target_gene"]
                                   for r in csv.DictReader(fh)} - {CONTROL_PERT})

    def fmt(names):
        return "[\n" + "".join(f'  "{n}",\n' for n in names) + "]"

    with open(TOML_PATH, "w") as fh:
        fh.write(f'''# Generated by src/state_norm.py -- log1p(CP{int(TARGET_SUM)}) copies.

[datasets]
vcc2025 = "{NORM_DIR}"

[training]
vcc2025 = "train"

[zeroshot]

[fewshot]

[fewshot."vcc2025.{CELL_TYPE}"]
val = {fmt(perts["val"])}
test = {fmt(perts["test"])}
''')
    VOL.commit()
    print(f"\nwrote {TOML_PATH}")
    print(f"{NORM_DIR}: {sorted(os.listdir(NORM_DIR))}")
    return TOML_PATH


@app.function(
    image=cpu_image, volumes={VOL_PATH: VOL},
    cpu=2.0, memory=8192, timeout=60 * 20,
)
def check():
    """Confirm the copies really are log1p(CP10k) before training on them."""
    import os

    import h5py
    import numpy as np

    for split, (h5, _) in SPLITS.items():
        for root, label in ((NORM_DIR, "norm"), (REHEARSAL, "raw ")):
            p = f"{root}/{h5}"
            if not os.path.exists(p):
                print(f"{label} {split}: MISSING")
                continue
            with h5py.File(p, "r") as h:
                d = h["X"]["data"][:2_000_000]
                indptr = h["X"]["indptr"][:]
                has_flag = "uns" in h and "log1p" in h["uns"]
                # First row's sum, which should be ~1e4 pre-log for the copies.
                a, b = int(indptr[0]), int(indptr[1])
                row = h["X"]["data"][a:b].astype(np.float64)
                lin = np.expm1(row) if label == "norm" else row
            print(f"{label} {split}: max {d.max():8.2f}  "
                  f"p99 {np.quantile(d, 0.99):7.2f}  "
                  f"mean {d.mean():6.3f}  uns/log1p={has_flag}  "
                  f"row0 linear sum {lin.sum():9.0f}")


@app.local_entrypoint()
def main(force: bool = False, block: bool = False, verify: bool = False):
    if verify:
        check.remote()
        return
    if block:
        normalize.remote(force)
        return
    print("spawned:", normalize.spawn(force).object_id)
